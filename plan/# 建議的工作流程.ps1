# ==========================================
# 建議的 Git 工作流程與版本控制指南
# ==========================================
# 這個指南將幫助你確保程式碼不會被洗掉，且能精細地記錄每個功能的開發歷程。

# ------------------------------------------
# 1. 核心觀念：使用開發分支
# ------------------------------------------
# 不要在 main 分支上直接開發。main 分支應該永遠保持穩定、隨時可以發布的狀態。
# 請將所有新功能與修改放在 `dev` (或功能專屬) 分支上。

# ------------------------------------------
# 2. 日常開發流程 (小步快跑、精細提交)
# ------------------------------------------

# a. 開始工作前，先拉取最新的遠端更新並切換到 dev 分支
git checkout dev
git pull origin dev

# b. 進行開發工作（編輯檔案）

# c. 查看變更狀態，精細挑選要提交的檔案
git status

# d. 暫存變更（盡量避免直接使用 git add .，除非你確定所有變更都要一起提交）
# 針對特定檔案暫存：
git add path/to/your/file.js
# 或是針對部分程式碼片段暫存（進階，會逐段詢問）：
git add -p

# e. 提交變更（使用有意義、單一邏輯的訊息）
# 命名慣例建議：
# feat: 新增了某個功能
# fix: 修復了某個 Bug
# refactor: 重構程式碼（無新增功能或修正 bug）
# docs: 更新文件
git commit -m "feat: 新增個人任務同步功能"

# f. 將目前的進度推送到遠端備份
git push origin dev

# ------------------------------------------
# 3. 功能完成後：合併回主分支 (main) 的流程
# ------------------------------------------

# a. 確保 dev 上的改動都已經 commit 完畢
git status

# b. 切換回主分支
git checkout main

# c. 提取遠端最新狀態（防止衝突）
git pull origin main

# d. 將 dev 分支的內容合併到主分支
git merge dev

# （如果此時出現衝突 Conflict，請打開程式碼編輯器解決衝突後，執行 git add . 與 git commit）

# e. 將合併後的結果推送到遠端
git push origin main

# ------------------------------------------
# 4. 版本發布：命名與建立版本標籤 (Tag)
# ------------------------------------------
# 合併到 main 後，我們通常會打上「版本標籤」作為里程碑，方便未來回溯。

# 命名慣例 (語意化版本)：v主版號.次版號.修訂號
# 主版號 (Major): v2.0.0 (不相容的 API 修改或架構大翻新)
# 次版號 (Minor): v1.2.0 (新增向下相容的功能)
# 修訂號 (Patch): v1.2.3 (向下相容的 Bug 修復)

# a. 在 main 分支上建立帶有註解的標籤
git tag -a v1.0.0 -m "Release v1.0.0: 新增了各裝置同步限制與完整的任務總覽頁面"

# b. 將單一標籤推送到遠端伺服器
git push origin v1.0.0
# （或是將所有本地標籤一次推送到遠端：git push origin --tags）

# ------------------------------------------
# 5. 繼續下一個功能的開發
# ------------------------------------------
# 發布完成後，切回 dev 分支繼續新的開發：
git checkout dev
